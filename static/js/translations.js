document.addEventListener("DOMContentLoaded", () => {
    const langSelects = document.querySelectorAll(".lang-select");

    // Function to apply translation
    const applyTranslation = (lang) => {
        const dictionary = translations[lang] || translations["en"];
        
        for (const [key, selector] of Object.entries(elementMappings)) {
            const elements = document.querySelectorAll(selector);
            elements.forEach((el) => {
                if (dictionary[key]) {
                    el.innerHTML = dictionary[key];
                }
            });
        }
        
        // Update all select dropdowns to reflect the current language choice
        langSelects.forEach((select) => {
            select.value = lang;
        });
        
        // Save language preference in localStorage
        localStorage.setItem("preferred_language", lang);
    };

    // Listen for dropdown changes
    langSelects.forEach((select) => {
        select.addEventListener("change", (e) => {
            const selectedLang = e.target.value || e.target.options[e.target.selectedIndex].text.toLowerCase();
            let langCode = 'en';
            if (selectedLang.includes('hi')) langCode = 'hi';
            if (selectedLang.includes('hinglish')) langCode = 'hinglish';
            
            applyTranslation(langCode);
        });
    });

    // Check localStorage for saved preference
    const savedLang = localStorage.getItem("preferred_language") || "en";
    applyTranslation(savedLang);
});
